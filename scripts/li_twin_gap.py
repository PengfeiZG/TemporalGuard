"""Attack-versus-twin gap tables for the LogicInception-style pilot, from the per-episode dumps.

For every judge, variant and strategy this counts, over the 36 sessions of the three families:

* attack flagged: the chain's own text was flagged (at one of its outputs, or named by a flag);
* twin flagged:   the benign twin's own text was flagged, in the same session positions;
* gap:            attack flagged minus twin flagged, with a bootstrap interval over the 12 chains.

Flags on unrelated filler are NOT counted: 11 to 22% of sessions are flagged on AgentDojo's own filler
text whatever the chain is, and the raw "false-alarm rate by benign family" in the result tables
includes them. Failed judge calls (stage `judge_error`) are ignored, which gives the same result as
counting them as flags for the Sonnet refusals (checked).

Usage (from the repository root):  python scripts/li_twin_gap.py [--out runs/li_twin_gap_summary.md]
"""

from __future__ import annotations

import argparse
import json
import random
from collections import defaultdict
from pathlib import Path

JUDGES = [  # (label, file stem in runs/)
    ("Haiku", "claude"), ("Luna", "openai"), ("Sonnet", "sonnet"), ("Sol", "sol"),
    ("Gemini Pro", "gemini_pro"), ("Gemini Flash-Lite", "gemini_flash"),
]  # fmt: skip
STRATEGIES = ["per_message", "fib_min3_fallback_confirm", "full"]
SHORT = {"per_message": "single read", "fib_min3_fallback_confirm": "final design", "full": "full history"}


def load(path: Path) -> list[dict]:
    with path.open(encoding="utf-8") as fh:
        return [json.loads(line) for line in fh if line.strip()]


def chain_flagged(record: dict, positions: set[int]) -> bool:
    """Was any flagged decision at, or naming, one of the chain's own outputs?"""
    for d in record["decisions"]:
        if d["stage"] == "judge_error" or d["verdict"] == "allow":
            continue
        if d["output_index"] in positions or positions & set(d["fragment_indices"]):
            return True
    return False


def paired(rows: list[dict]) -> list[tuple[str, int, dict, dict]]:
    by = {(r["strategy"], r["episode_id"]): r for r in rows}
    out = []
    for (strategy, eid), r in by.items():
        if "_twin" in r["family"]:
            out.append((strategy, int(eid.rsplit("-", 1)[1]) % 12, r, by[(strategy, eid.replace("_twin", "", 1))]))
    return out


def bootstrap(per_chain: dict[int, list[float]], n: int = 4000, seed: int = 0) -> tuple[float, float, float]:
    rng = random.Random(seed)
    means = [sum(v) / len(v) for v in per_chain.values()]
    draws = sorted(sum(rng.choice(means) for _ in means) / len(means) for _ in range(n))
    return sum(means) / len(means), draws[int(0.025 * n)], draws[int(0.975 * n)]


def cell(rows: list[dict], strategy: str) -> tuple[float, float, dict[int, list[float]]]:
    per: dict[int, list[float]] = defaultdict(list)
    attack = twin = count = 0
    for s, chain, t, a in paired(rows):
        if s != strategy:
            continue
        positions = set(a["attack_indices"])
        fa, ft = chain_flagged(a, positions), chain_flagged(t, positions)
        per[chain].append(float(fa) - float(ft))
        attack += fa
        twin += ft
        count += 1
    return attack / count, twin / count, per


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--runs", default="runs")
    ap.add_argument("--out", default=None, help="write the Markdown here (default: print)")
    args = ap.parse_args()
    runs = Path(args.runs)
    lines = ["# LogicInception-style pilot: attack flagged versus twin flagged", "",
             "Generated by `scripts/li_twin_gap.py` from the `li?_twin_*_dump.jsonl` files. Each cell is "
             "attack flagged / twin flagged, then the gap with a 95% bootstrap interval over the 12 chains.",
             "Only flags on the chain's own text count; see the script's docstring.", ""]  # fmt: skip
    cache: dict[tuple[str, str], list[dict]] = {}
    for variant, title in (("A", "Variant A (descriptive voice)"), ("B", "Variant B (notice voice)")):
        lines += [f"## {title}", "", "| judge | " + " | ".join(SHORT[s] for s in STRATEGIES) + " |", "|---|---|---|---|"]
        for label, stem in JUDGES:
            path = runs / f"li{variant}_twin_{stem}_dump.jsonl"
            if not path.exists():
                continue
            cache[(label, variant)] = rows = load(path)
            cells = []
            for s in STRATEGIES:
                a, t, per = cell(rows, s)
                g, lo, hi = bootstrap(per)
                cells.append(f"{a:.2f} / {t:.2f}: **{g:+.2f}** [{lo:+.2f}, {hi:+.2f}]")
            lines.append(f"| {label} | " + " | ".join(cells) + " |")
        lines.append("")
    lines += ["## Final design minus full history (paired over the 12 chains; positive: final design discriminates better)", "",
              "| judge | variant A | variant B |", "|---|---|---|"]  # fmt: skip
    for label, _ in JUDGES:
        out = []
        for variant in "AB":
            rows = cache.get((label, variant))
            if rows is None:
                out.append("n/a")
                continue
            _, _, pf = cell(rows, "fib_min3_fallback_confirm")
            _, _, pu = cell(rows, "full")
            d, lo, hi = bootstrap({k: [x - y for x, y in zip(pf[k], pu[k], strict=False)] for k in pf})
            out.append(f"{d:+.2f} [{lo:+.2f}, {hi:+.2f}]")
        lines.append(f"| {label} | " + " | ".join(out) + " |")
    text = "\n".join(lines) + "\n"
    if args.out:
        Path(args.out).write_text(text, encoding="utf-8")
        print(f"wrote {args.out}")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
